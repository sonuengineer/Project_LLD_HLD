// Rebuilds the "measured" section of ../README.md (between <!-- MEASURED:START --> and <!-- MEASURED:END -->) from the
// raw result files in bench/reference-results/<run>/. Each bN.json holds the title, note, columns and rows that run.mjs
// generated from that experiment's raw data, so nothing in that README section is typed by hand.
//   node update-readme.mjs <run-folder> [<run-folder> ...]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { HERE, ROOT } from "./lib.mjs";

const runs = process.argv.slice(2);
if (runs.length === 0) throw new Error("usage: node update-readme.mjs <reference-results folder> ...");

const table = (columns, rows) =>
  [`| ${columns.join(" | ")} |`, `|${columns.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map((c) => String(c ?? "-").replace(/\|/g, "/")).join(" | ")} |`)].join("\n");

const parts = [];
for (const run of runs) {
  const dir = path.join(HERE, "reference-results", run);
  const env = JSON.parse(readFileSync(path.join(dir, "env.json"), "utf8"));
  const steal = env.cpuShareDuringRun
    ? `${env.cpuShareDuringRun.steal}%`
    : "not recorded (the run did not reach its end, see the deployment doc)";
  parts.push(
    `### Run \`${run}\``,
    "",
    `${env.date.slice(0, 10)}, ${env.platform}, ${env.cpus} CPUs (${env.cpuModel.trim()}), Node ${env.node}, commit \`${env.commit}\`, ` +
      `${env.runs} run(s) per measurement, CPU steal over the run: ${steal}. Topology: ${env.topology}. ` +
      `Raw data: \`bench/reference-results/${run}/\`.`,
    "",
  );
  const files = readdirSync(dir).filter((f) => /^b\d+\.json$/.test(f)).sort();
  for (const f of files) {
    const r = JSON.parse(readFileSync(path.join(dir, f), "utf8"));
    if (r.skipped || r.failed || !r.rows) {
      parts.push(`#### ${f}`, "", r.skipped ? `Skipped: ${r.skipped}` : "FAILED (see the raw file).", "");
      continue;
    }
    parts.push(`#### ${r.title}`, "", r.note, "", table(r.columns, r.rows), "", `Raw: \`${f}\``, "");
  }
  const extra = path.join(dir, "b7-remote-brokers.json");
  if (existsSync(extra)) {
    const x = JSON.parse(readFileSync(extra, "utf8"));
    const row = (name, s, mm) => [name, s.connections, s.subscriptions, s.remoteInterest, s.routes, Math.round(mm[0] / 1024), Math.round(mm[1] / 1024)];
    parts.push(
      "#### B7 continued: the two REMOTE brokers after the soak (from their own logs)",
      "",
      x.note,
      "",
      table(
        ["broker", "connections after", "subscriptions after", "remote interest after", "routes (to each other)", "RSS min MiB", "RSS max MiB"],
        [row("B (micro, x86)", x.brokerB_micro, x.brokerB_rssKiB_min_max), row("C (A1, ARM)", x.brokerC_a1, x.brokerC_rssKiB_min_max)],
      ),
      "",
      "Raw: `b7-remote-brokers.json`",
      "",
    );
  }
}

const readmePath = path.join(ROOT, "README.md");
const readme = readFileSync(readmePath, "utf8");
const start = "<!-- MEASURED:START -->";
const end = "<!-- MEASURED:END -->";
const i = readme.indexOf(start);
const j = readme.indexOf(end);
if (i < 0 || j < i) throw new Error("README.md has no MEASURED markers");
const generated = `${start}\n<!-- generated by bench/update-readme.mjs from bench/reference-results; do not edit by hand -->\n\n${parts.join("\n")}\n${end}`;
writeFileSync(readmePath, readme.slice(0, i) + generated + readme.slice(j + end.length));
console.log(`README.md: measured section rebuilt from ${runs.length} run(s)`);
